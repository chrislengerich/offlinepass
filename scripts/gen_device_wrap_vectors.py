#!/usr/bin/env python3
"""Generates fixed test vectors for the linuxpass device-wrap protocol
(Plan 2, docs/extension-protocol.md) so the Android (JCE) and extension
(WebCrypto) implementations can be cross-checked against each other.

Vector chain (all inputs fixed):
  prfOut  : what a WebAuthn PRF (hmac-secret) eval returns — 32 bytes
  salt    : SHA-256("linuxpass-device-v1" || rawCredentialId)
  kek     : HKDF-SHA256(ikm=prfOut, salt, info="linuxpass-seed-kek-v1")
  seedKey : ECDH P-256 keypair; pkcs8(seedKey) AES-256-GCM'd under kek
  shared  : ECDH(ephemeral_priv, seed_pub)
  wrapKek : HKDF-SHA256(ikm=shared.x, salt=keyId-bytes, info="linuxpass-paste-wrap-v1")
  ct      : AES-256-GCM(wrapKek, iv, aad, payload)

Run:  python3 scripts/gen_device_wrap_vectors.py
"""
import hashlib
import hmac
import json
import base64
import textwrap

from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.serialization import (
    Encoding, PrivateFormat, NoEncryption, PublicFormat)

# --- fixed inputs ----------------------------------------------------------
PRF_OUT = bytes(range(32))                                  # fake PRF output
CRED_ID = bytes(range(32, 64))                              # fake credentialId
SEED_IV = bytes.fromhex("000102030405060708090a0b")         # wrap-storage iv
WRAP_IV = bytes.fromhex("0102030405060708090a0b0c")         # paste iv
SEED_SCALAR = int.from_bytes(hashlib.sha256(b"device-seed").digest(), "big") % ec.SECP256R1().group_order
EPH_SCALAR = int.from_bytes(hashlib.sha256(b"ephemeral").digest(), "big") % ec.SECP256R1().group_order
PAYLOAD = json.dumps({
    "itemId": "vec-item-0000", "shareId": "local",
    "data": {"type": "login",
             "metadata": {"name": "Vector Test", "itemUuid": "vec-item-0000"},
             "content": {"itemEmail": "", "itemUsername": "vector",
                         "password": "s3cret-vector", "urls": ["https://example.test"],
                         "totpUri": "", "passkeys": []}},
    "state": 1}, separators=(",", ":"))

# --- HKDF (RFC 5869) on stdlib primitives — vector generation only ---------
def hkdf(ikm, salt, info, length=32):
    prk = hmac.new(salt or b"\x00" * 32, ikm, hashlib.sha256).digest()
    okm, t, i = b"", b"", 1
    while len(okm) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        okm += t; i += 1
    return okm[:length]

def b64(b): return base64.b64encode(b).decode()
def b64u(b): return base64.urlsafe_b64encode(b).rstrip(b"=").decode()

# --- protocol chain ---------------------------------------------------------
salt = hashlib.sha256(b"linuxpass-device-v1" + CRED_ID).digest()
kek = hkdf(PRF_OUT, salt, b"linuxpass-seed-kek-v1")

seed_key = ec.derive_private_key(SEED_SCALAR, ec.SECP256R1())  # pinned scalar
seed_priv_int = seed_key.private_numbers().private_value       # vector pins it
seed_pub_raw = seed_key.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)

seed_priv = ec.derive_private_key(seed_priv_int, ec.SECP256R1())
seed_pkcs8 = seed_priv.private_bytes(Encoding.DER, PrivateFormat.PKCS8, NoEncryption())
seed_ct = AESGCM(kek).encrypt(SEED_IV, seed_pkcs8, b"linuxpass-seed-wrap-v1")

key_id = hashlib.sha256(seed_pub_raw).digest()[:8].hex()
eph_priv = ec.derive_private_key(EPH_SCALAR, ec.SECP256R1())
eph_pub_raw = eph_priv.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
shared_x = eph_priv.exchange(ec.ECDH(), seed_priv.public_key())
wrap_kek = hkdf(shared_x, bytes.fromhex(key_id), b"linuxpass-paste-wrap-v1")
aad = ("linuxpass-paste-wrap-v1:" + key_id + ":" + b64(eph_pub_raw)).encode()
ct = AESGCM(wrap_kek).encrypt(WRAP_IV, PAYLOAD.encode(), aad)

wrapped = {
    "v": 1,
    "type": "linuxpass-wrap",
    "wrap": {"keyId": key_id, "epk": b64(eph_pub_raw)},
    "iv": b64(WRAP_IV),
    "ct": b64(ct),
}
wrapped_json = json.dumps(wrapped, separators=(",", ":"))

device_record = {
    "id": key_id, "name": "vector-key", "credId": b64(CRED_ID),
    "pub": b64(seed_pub_raw), "keyId": key_id, "added": 1762500000,
    "salt": b64(salt), "wrapped": {"iv": b64(SEED_IV), "ct": b64(seed_ct)},
}
record_json = json.dumps({"type": "linuxpass-device", "device": device_record}, separators=(",", ":"))

def block(title, obj):
    print(f"--- {title} ---")
    if isinstance(obj, str):
        print(textwrap.fill(obj, 96))
    else:
        print(json.dumps(obj, indent=2))
    print()

print("# Auto-generated by scripts/gen_device_wrap_vectors.py — do not edit by hand.")
block("hex inputs", {
    "prfOut": PRF_OUT.hex(), "credId": CRED_ID.hex(), "salt": salt.hex(),
    "kek": kek.hex(), "seedPrivScalar": hex(seed_priv_int),
    "seedPubRaw": seed_pub_raw.hex(), "seedPkcs8Sha256": hashlib.sha256(seed_pkcs8).hexdigest(),
    "ephScalar": hex(EPH_SCALAR), "ephPubRaw": eph_pub_raw.hex(),
    "sharedX": shared_x.hex(), "wrapKek": wrap_kek.hex(),
    "seedIv": SEED_IV.hex(), "wrapIv": WRAP_IV.hex(), "aad": aad.decode(),
})
block("device record (QRFT payload the pair page emits)", record_json)
block("wrapped paste (QRFT payload the export flow emits)", wrapped_json)
print("--- expected decrypt (Android + extension must both produce) ---")
print(PAYLOAD)

package com.linuxpass.app.ui

import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.linuxpass.app.vault.PasswordGen
import com.linuxpass.app.vault.ProtonItem

/**
 * Add-entry flow (TUI parity): URL + username, optional SimpleLogin-style
 * alias stub, generated password. The parent applies VaultSession.save.
 */
@Composable
fun AddEntryScreen(onCancel: () -> Unit, onSave: (ProtonItem) -> Unit) {
    var url by remember { mutableStateOf("") }
    var username by remember { mutableStateOf("") }
    var useAlias by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf(PasswordGen.password()) }
    var showPassword by remember { mutableStateOf(true) }
    val alias = remember { PasswordGen.alias() }

    Column(
        modifier = Modifier.fillMaxSize().padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        Text("Add entry", style = MaterialTheme.typography.titleLarge)
        OutlinedTextField(value = url, onValueChange = { url = it }, label = { Text("URL") }, singleLine = true)
        if (!useAlias) {
            OutlinedTextField(
                value = username, onValueChange = { username = it },
                label = { Text("Username") }, singleLine = true
            )
        }
        Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) {
            Checkbox(checked = useAlias, onCheckedChange = { useAlias = it })
            Text("Email alias (SimpleLogin stub)")
        }
        if (useAlias) Text("Alias: $alias\nNote: Created via linuxpass (SimpleLogin stub)",
            style = MaterialTheme.typography.bodySmall)
        Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Text("Password: ${if (showPassword) generated else "•".repeat(generated.length)}")
            TextButton(onClick = { showPassword = !showPassword }) {
                Text(if (showPassword) "Hide" else "Show")
            }
            TextButton(onClick = { generated = PasswordGen.password() }) { Text("Regen") }
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Button(onClick = {
                if (url.isBlank()) return@Button
                onSave(ProtonItem(
                    name = "",
                    username = if (useAlias) "" else username,
                    email = if (useAlias) alias else "",
                    password = generated,
                    urls = listOf(url).filter { it.isNotBlank() },
                    note = if (useAlias) "Created via linuxpass (SimpleLogin stub)" else ""
                ))
            }, enabled = url.isNotBlank()) { Text("Save") }
            OutlinedButton(onClick = onCancel) { Text("Cancel") }
        }
    }
}

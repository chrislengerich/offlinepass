package com.offlinepass.app.ui

import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import kotlinx.coroutines.launch
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.text.input.VisualTransformation
import androidx.compose.ui.unit.dp
import com.offlinepass.app.simplelogin.SimpleLoginHttp
import com.offlinepass.app.vault.VaultSession
import com.offlinepass.app.vault.PasswordGen
import com.offlinepass.app.vault.ProtonItem

/** The stub note the alias flow carries (TUI parity); user-editable. */
private const val ALIAS_NOTE = "Created via offlinepass (SimpleLogin stub)"

/**
 * Add-entry flow (TUI parity): URL + username, optional SimpleLogin-style
 * alias stub, an editable (generated) password, and a notes field. The
 * parent applies VaultSession.save.
 */
@Composable
fun AddEntryScreen(
    onCancel: () -> Unit,
    onSave: (ProtonItem) -> Unit,
    /** The autofill save-offer's prefill (the notification's tap). */
    initial: ProtonItem? = null
) {
    var url by remember { mutableStateOf(initial?.urls?.firstOrNull() ?: "") }
    var username by remember { mutableStateOf(initial?.username ?: "") }
    var useAlias by remember { mutableStateOf(false) }
    var generated by remember {
        mutableStateOf(initial?.password?.takeIf { it.isNotBlank() } ?: PasswordGen.password())
    }
    var showPassword by remember { mutableStateOf(true) }
    var note by remember { mutableStateOf("") }
    val alias = remember { PasswordGen.alias() }

    // THE REAL SIMPLELOGIN ALIAS (when linked): the link under the URL
    // creates a REAL alias on the SL account (the hostname = the URL's
    // domain) — it rides the email field on the save. The items carry
    // no SL state; this = the explicit user action.
    var slAlias by remember { mutableStateOf<String?>(null) }
    var slBusy by remember { mutableStateOf(false) }
    var slError by remember { mutableStateOf<String?>(null) }
    val slLinked = VaultSession.simpleLoginItem() != null
    val slScope = androidx.compose.runtime.rememberCoroutineScope()

    Column(
        modifier = Modifier.fillMaxSize().padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        Text("Add entry", style = MaterialTheme.typography.titleLarge)
        OutlinedTextField(value = url, onValueChange = { url = it }, label = { Text("URL") }, singleLine = true)
        if (slLinked) {
            Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) {
                TextButton(onClick = {
                    val apiKey = VaultSession.simpleLoginItem()?.password ?: return@TextButton
                    val host = runCatching {
                        java.net.URI(url.trim().let { if (it.contains("://")) it else "https://$it" }).host
                    }.getOrNull()
                    slBusy = true; slError = null
                    slScope.launch {
                        try {
                            // THE PASSMAIL.NET-PINNED CREATION: the v5
                            // options (the hostname = the entry's site)
                            // → the signed passmail.net suffix → the
                            // v3 custom/new with the default mailbox.
                            val opts = SimpleLoginHttp().aliasOptions(apiKey, host)
                            if (!opts.canCreate) throw Exception(
                                "SimpleLogin: the alias limit is reached")
                            val suffix = opts.suffixes.firstOrNull {
                                it.suffix.endsWith("@${VaultSession.SL_ALIAS_DOMAIN}")
                            } ?: throw Exception(
                                "the SimpleLogin account has no ${VaultSession.SL_ALIAS_DOMAIN} domain")
                            val mailbox = SimpleLoginHttp().mailboxes(apiKey)
                                .firstOrNull { it.isDefault } ?: SimpleLoginHttp()
                                .mailboxes(apiKey).first()
                            val created = SimpleLoginHttp().createCustomAlias(
                                apiKey,
                                prefix = opts.prefixSuggestion
                                    ?: host?.substringBefore(".") ?: "alias",
                                signedSuffix = suffix.signedSuffix,
                                mailboxIds = listOf(mailbox.id),
                                hostname = host)
                            slAlias = created.email
                        } catch (e: Exception) {
                            slError = "SimpleLogin error: ${e.message}"
                        }; slBusy = false
                    }
                }, enabled = !slBusy) {
                    Text(if (slBusy) "Creating alias…" else "✨ SimpleLogin alias")
                }
            }
            if (slAlias != null) Text(
                "Alias: $slAlias (created on SimpleLogin - ${VaultSession.SL_ALIAS_DOMAIN})",
                style = MaterialTheme.typography.bodySmall)
            slError?.let { Text(it, style = MaterialTheme.typography.bodySmall) }
        }
        if (!useAlias) {
            OutlinedTextField(
                value = username, onValueChange = { username = it },
                label = { Text("Username") }, singleLine = true
            )
        }
        Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) {
            Checkbox(checked = useAlias, onCheckedChange = { checked ->
                useAlias = checked
                // The alias stub rides in the note field — kept editable,
                // prepended when the user already wrote their own note.
                if (checked && !note.contains(ALIAS_NOTE)) {
                    note = if (note.isBlank()) ALIAS_NOTE else "$ALIAS_NOTE\n$note"
                }
            })
            Text("Email alias (SimpleLogin stub)")
        }
        if (useAlias) Text("Alias: $alias", style = MaterialTheme.typography.bodySmall)
        OutlinedTextField(
            value = generated, onValueChange = { generated = it },
            label = { Text("Password") }, singleLine = true,
            visualTransformation = if (showPassword) VisualTransformation.None
                                   else PasswordVisualTransformation(),
            trailingIcon = {
                TextButton(onClick = { showPassword = !showPassword }) {
                    Text(if (showPassword) "Hide" else "Show")
                }
            },
            modifier = Modifier.fillMaxWidth()
        )
        TextButton(onClick = { generated = PasswordGen.password() }) { Text("Regen") }
        OutlinedTextField(
            value = note, onValueChange = { note = it },
            label = { Text("Notes") },
            modifier = Modifier.fillMaxWidth()
        )
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Button(onClick = {
                if (url.isBlank()) return@Button
                onSave(ProtonItem(
                    name = "",
                    username = if (useAlias) "" else username,
                    email = slAlias ?: if (useAlias) alias else "",
                    password = generated,
                    urls = listOf(url).filter { it.isNotBlank() },
                    note = note
                ))
            }, enabled = url.isNotBlank()) { Text("Save") }
            OutlinedButton(onClick = onCancel) { Text("Cancel") }
        }
    }
}
